// Reproducible, font-independent SVG masters. The wordmark uses Noto Sans Black
// outlines (SIL OFL); the J and the speech-bubble monogram are custom paths.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const require = createRequire(new URL('../../functions/package.json', import.meta.url));
const fontkit = require('@pdf-lib/fontkit');
const font = fontkit.create(readFileSync(require.resolve('@fontsource/noto-sans/files/noto-sans-latin-900-normal.woff')));
const markPaths = [
  { ink: 'accent', d: 'M104 8Q112 5 120 10L181 44Q194 51 194 66V138Q194 153 179 157L78 180L20 199L28 163L21 161Q6 157 6 141V65Q6 50 21 45ZM106 26L27 62Q24 63 24 69V137Q24 142 30 144L49 150L45 170L72 162L175 139Q176 138 176 134V69Q176 64 172 62L111 27Q109 25 106 26Z' },
  { ink: 'primary', d: 'M53 62L88 50V113Q88 142 62 144Q37 146 33 121L53 115Q54 126 62 126Q70 126 70 114V76L53 81Z' },
  { ink: 'accent', d: 'M119 73L155 61L124 99L156 132L138 140L100 105V92Z' },
];
const paths = [...markPaths, { ink: 'primary', d: 'M274 36H309V117Q309 160 269 160Q239 160 224 138L250 118Q256 131 268 131Q274 131 274 117Z' }];
const run = font.layout('ustKvíz');
const scale = .145;
let cursor = 321;
const round = n => +n.toFixed(2);
for (let index = 0; index < run.glyphs.length; index++) {
  const glyph = run.glyphs[index], pos = run.positions[index];
  const d = glyph.path.commands.map(({command,args}) => {
    const letter = {moveTo:'M',lineTo:'L',quadraticCurveTo:'Q',bezierCurveTo:'C',closePath:'Z'}[command];
    if (!letter) throw new Error('Unsupported font path command: '+command);
    return letter + args.map((n,i) => round(i%2 ? 155-(n+pos.yOffset)*scale : cursor+(n+pos.xOffset)*scale)).join(' ');
  }).join('');
  paths.push({ink:index<3?'primary':'accent',d});
  cursor += pos.xAdvance*scale;
}
const brandArtwork = {viewBox:{width:880,height:200},paths,markViewBox:{width:200,height:200},markPaths};
mkdirSync('apps/web/public/brand',{recursive:true});
writeFileSync('packages/quiz-domain/src/brand-artwork.ts', '// Generated by tools/brand/generate.mjs. All coordinates are outlined, with no runtime font dependency.\nexport const brandArtwork = '+JSON.stringify(brandArtwork,null,2)+' as const;\n');
const colors={dark:{primary:'#F8FAFC',accent:'#FFC107'},light:{primary:'#0B1220',accent:'#B87900'},mono:{primary:'#0B1220',accent:'#0B1220'},white:{primary:'#FFFFFF',accent:'#FFFFFF'}};
function svg(parts,box,palette,backing='') {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${box.width} ${box.height}" role="img" aria-label="JustKvíz"><title>JustKvíz</title>${backing}${parts.map(p=>`<path fill="${palette[p.ink]}" d="${p.d}"/>`).join('')}</svg>\n`;
}
for(const [variant,palette] of Object.entries(colors)) writeFileSync(`apps/web/public/brand/justkviz-${variant}.svg`,svg(paths,brandArtwork.viewBox,palette));
writeFileSync('apps/web/public/brand/justkviz-mark.svg',svg(markPaths,brandArtwork.markViewBox,colors.dark));
writeFileSync('apps/web/public/brand/justkviz-icon.svg',svg(markPaths,brandArtwork.markViewBox,colors.dark,'<rect width="200" height="200" rx="38" fill="#0B1220"/>'));
copyFileSync(require.resolve('@fontsource/noto-sans/LICENSE'),'apps/web/public/brand/NOTO-LICENSE.txt');
console.log('Generated shared paths and six SVG masters.');
